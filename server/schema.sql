CREATE TABLE IF NOT EXISTS clients (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, company text NOT NULL DEFAULT '', email text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '', notes text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text),
  updated_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text)
);
CREATE TABLE IF NOT EXISTS products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, sku text NOT NULL DEFAULT '', description text NOT NULL DEFAULT '',
  price_cents integer NOT NULL CHECK (price_cents >= 0), active integer NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
  created_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text),
  updated_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text)
);
CREATE TABLE IF NOT EXISTS opportunities (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL, client_id integer NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
  value_cents integer NOT NULL DEFAULT 0 CHECK (value_cents >= 0),
  stage text NOT NULL DEFAULT 'novo' CHECK (stage IN ('novo','contato','proposta','negociacao','ganho','perdido')),
  notes text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text),
  updated_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text)
);
CREATE TABLE IF NOT EXISTS proposals (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL, client_id integer NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
  opportunity_id integer REFERENCES opportunities(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'rascunho' CHECK (status IN ('rascunho','enviada','aceita','recusada')),
  valid_until text NOT NULL DEFAULT '', delivery_date text NOT NULL DEFAULT '', notes text NOT NULL DEFAULT '',
  discount_percent double precision NOT NULL DEFAULT 0 CHECK (discount_percent >= 0 AND discount_percent <= 100),
  subtotal_cents integer NOT NULL DEFAULT 0, total_cents integer NOT NULL DEFAULT 0,
  created_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text),
  updated_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text)
);
CREATE TABLE IF NOT EXISTS proposal_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proposal_id integer NOT NULL REFERENCES proposals(id) ON DELETE CASCADE,
  product_id integer REFERENCES products(id) ON DELETE SET NULL,
  description text NOT NULL, quantity integer NOT NULL CHECK (quantity > 0),
  unit_price_cents integer NOT NULL CHECK (unit_price_cents >= 0)
);
CREATE TABLE IF NOT EXISTS activities (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL, client_id integer REFERENCES clients(id) ON DELETE SET NULL,
  due_date text NOT NULL, notes text NOT NULL DEFAULT '', completed integer NOT NULL DEFAULT 0 CHECK (completed IN (0,1)),
  created_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text),
  updated_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text)
);
CREATE TABLE IF NOT EXISTS client_interactions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id integer NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  opportunity_id integer REFERENCES opportunities(id) ON DELETE SET NULL,
  type text NOT NULL CHECK (type IN ('ligacao','email','reuniao','mensagem','outro')),
  description text NOT NULL, occurred_at text NOT NULL, scheduled_at text NOT NULL DEFAULT '',
  completed integer NOT NULL DEFAULT 0 CHECK (completed IN (0,1)),
  funnel_stage text NOT NULL DEFAULT '' CHECK (funnel_stage = '' OR funnel_stage IN ('novo','contato','proposta','negociacao','ganho','perdido')),
  created_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text)
);
CREATE INDEX IF NOT EXISTS idx_opportunities_client ON opportunities(client_id);
CREATE INDEX IF NOT EXISTS idx_proposals_client ON proposals(client_id);
CREATE INDEX IF NOT EXISTS idx_proposal_items_proposal ON proposal_items(proposal_id);
CREATE INDEX IF NOT EXISTS idx_activities_due ON activities(completed, due_date);
CREATE INDEX IF NOT EXISTS idx_client_interactions_client_date ON client_interactions(client_id, occurred_at DESC);
CREATE TABLE IF NOT EXISTS schema_migrations (
  key text PRIMARY KEY, applied_at text NOT NULL DEFAULT (CURRENT_TIMESTAMP::timestamp(0)::text)
);
